    def test_static_preview_loads_script_and_explains_login(self):
        from pathlib import Path
        from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
        from functools import partial
        import threading

        root = Path(__file__).resolve().parents[2]
        handler = partial(SimpleHTTPRequestHandler, directory=str(root))
        server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            self.page.goto(f"http://127.0.0.1:{server.server_address[1]}/HW2/static/index.html")
            expect(self.page.locator("#connection-help")).to_be_visible()
            expect(self.page.locator("#login-error")).to_contain_text("無法連接校務登入服務")
            self.page.get_by_role("button", name="顯示", exact=True).click()
            expect(self.page.get_by_label("密碼", exact=True)).to_have_attribute("type", "text")
            self.page.get_by_role("button", name="隱藏", exact=True).click()
            expect(self.page.get_by_label("密碼", exact=True)).to_have_attribute("type", "password")
            self.page.get_by_label("帳號", exact=True).fill("student1")
            self.page.get_by_label("密碼", exact=True).fill("student123")
            self.page.get_by_role("button", name="登入", exact=True).click()
            expect(self.page.locator("#login-error")).to_contain_text("無法連接校務登入服務")
            expect(self.page.locator("#portal")).not_to_be_visible()
            self.page.goto((root / "HW2/static/index.html").as_uri())
            expect(self.page.locator("#connection-help")).to_be_visible()
            self.page.get_by_role("button", name="顯示", exact=True).click()
            expect(self.page.get_by_label("密碼", exact=True)).to_have_attribute("type", "text")
        finally:
            server.shutdown()
            server.server_close()
            thread.join(timeout=5)
